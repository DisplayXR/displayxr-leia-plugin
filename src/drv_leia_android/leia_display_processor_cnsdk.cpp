// #522: the runtime's MANAGED/MANUAL selection. Forward to the CNSDK wrapper,
// which toggles NoFaceMode (with the licensing/availability guard).
void
set_eye_tracking_mode_cnsdk(struct xrt_display_processor *xdp, uint32_t mode)
{
	leia_dp_cnsdk *impl = as_impl(xdp);
	if (impl->cnsdk != nullptr) {
		leia_cnsdk_set_eye_tracking_mode(impl->cnsdk, mode);
	}
}

void
destroy_impl(struct xrt_display_processor *xdp)
{
	leia_dp_cnsdk *impl = as_impl(xdp);

	// Drain all in-flight GPU work (especially CNSDK's interlacer
	// submits) before destroying any handles CNSDK might still be
	// reading. Same defensive idiom as audit B6 — applies in atlas mode
	// because CNSDK still owns its own queue submit even though we
	// don't have a per-view image / blit cmd buffer to wait on.
	if (impl->vk != nullptr) {
		impl->vk->vkDeviceWaitIdle(impl->vk->device);
	}

	// Destroy CNSDK first (it may still reference our framebuffers via its
	// interlacer), then our weave destination (render pass + depth + cached
	// per-image views/framebuffers). Both are after the device-idle above.
	if (impl->cnsdk != nullptr) {
		leia_cnsdk_destroy(&impl->cnsdk);
	}
	destroy_weave_target(impl);
	destroy_alpha_gate(impl); // #568
	destroy_compose(impl);    // runtime#1073 T0
	free(impl);
}

