extern "C" xrt_result_t
leia_dp_factory_cnsdk(void *vk_bundle,
                      void *vk_cmd_pool,
                      void *window_handle,
                      int32_t target_format,
                      struct xrt_display_processor **out_xdp)
{
	(void)window_handle; (void)target_format;

	struct leia_cnsdk *cnsdk = nullptr;
	xrt_result_t ret = leia_cnsdk_create(&cnsdk);
	if (ret != XRT_SUCCESS || cnsdk == nullptr) {
		U_LOG_W("leia_cnsdk_create failed (%d), falling back to no-DP path", (int)ret);
		return ret != XRT_SUCCESS ? ret : XRT_ERROR_DEVICE_CREATION_FAILED;
	}

	leia_dp_cnsdk *impl = static_cast<leia_dp_cnsdk *>(calloc(1, sizeof(*impl)));
	if (impl == nullptr) {
		leia_cnsdk_destroy(&cnsdk);
		return XRT_ERROR_ALLOCATION;
	}

	impl->cnsdk = cnsdk;
	impl->vk = static_cast<struct vk_bundle *>(vk_bundle);
	impl->cmd_pool = (VkCommandPool)(uintptr_t)vk_cmd_pool;

	/* ABI major v2 (ADR-020): the 8-byte struct_size header tells the
	 * runtime how far this vtable extends. The runtime gates every optional
	 * slot below on XRT_DP_HAS_SLOT(xdp, field), bounded against this value —
	 * leave it 0 (calloc default) and is_self_submitting / on_pause / on_resume /
	 * eye-positions / display-dims all read as absent, silently regressing the
	 * self-submitting atlas path into a double-submit.
	 *
	 * #568: report sizeof(struct xrt_display_processor_vk), NOT sizeof(base),
	 * so the runtime also discovers the appended set_transparent_background slot
	 * (the VK/Android DP variant — the struct_size gate is the discriminator). */
	impl->dp_vk.base.struct_size = static_cast<uint32_t>(sizeof(struct xrt_display_processor_vk));
	impl->dp_vk.base.process_atlas = process_atlas_weave;
	impl->dp_vk.base.on_pause = on_pause_cnsdk;
	impl->dp_vk.base.on_resume = on_resume_cnsdk;
	impl->dp_vk.base.is_self_submitting = is_self_submitting_true;
	impl->dp_vk.base.set_target_color_view = set_target_color_view_cnsdk;
	impl->dp_vk.base.get_predicted_eye_positions = get_predicted_eye_positions_ipd;
	impl->dp_vk.base.get_display_dimensions = get_display_dimensions_default;
	impl->dp_vk.base.get_display_pixel_info = get_display_pixel_info_default;
	impl->dp_vk.base.set_eye_tracking_mode = set_eye_tracking_mode_cnsdk; // #522
	impl->dp_vk.base.destroy = destroy_impl;
	impl->dp_vk.set_transparent_background = set_transparent_background_cnsdk; // #568 (variant slot)
	// runtime#602 recreate notification (variant slot, inside struct_size above).
	// Without it the view-keyed fb caches survive a swapchain recreate and can
	// hit a recycled handle -- see notify_target_recreated_cnsdk.
	impl->dp_vk.notify_target_recreated = notify_target_recreated_cnsdk;
	// runtime#1073 T0: base slot 16 — the compose-under background seam. Already
	// inside struct_size (it is a BASE slot and we report
	// sizeof(xrt_display_processor_vk)), so no ABI bump — ADR-020 clean.
	impl->dp_vk.base.set_background_2d = set_background_2d_cnsdk;
#ifdef XRT_DP_VK_HAS_WINDOW_SCREEN_RECT
	// runtime#1033 / #150: per-window weave phase. struct_size above already
	// covers this slot (it is sizeof(xrt_display_processor_vk)), so filling the
	// pointer is all the runtime needs to discover it.
	impl->dp_vk.set_window_screen_rect = set_window_screen_rect_cnsdk;
#endif

	*out_xdp = &impl->dp_vk.base;

	U_LOG_W("Leia CNSDK DP created (atlas mode)");
	DXR_HW_DBG("factory: impl=%p vk=%p cnsdk=%p", (void *)impl, (void *)impl->vk, (void *)impl->cnsdk);
	return XRT_SUCCESS;
}
