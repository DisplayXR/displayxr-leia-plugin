// Get (or lazily create + cache) the output framebuffer for the upcoming target,
// wrapping the compositor's color view (pending_target_view) + ag_rp. We build
// NO image views on swapchain images ourselves (Adreno faults) — same contract
// as get_or_create_weave_fb. Returns VK_NULL_HANDLE on failure.
VkFramebuffer
alpha_gate_get_fb(leia_dp_cnsdk *impl, uint32_t w, uint32_t h)
{
	struct vk_bundle *vk = impl->vk;
	VkImageView color_view = impl->pending_target_view;
	if (color_view == VK_NULL_HANDLE) {
		return VK_NULL_HANDLE;
	}
	for (uint32_t i = 0; i < impl->ag_fb_count; i++) {
		if (impl->ag_fb_cache[i].view == color_view) {
			if (impl->ag_fb_cache[i].w == w && impl->ag_fb_cache[i].h == h) {
				return impl->ag_fb_cache[i].fb;
			}
			// Same view handle, different dims — the driver recycled a
			// destroyed view across a rotation (portrait⇄landscape). The
			// cached fb is the OLD orientation's size; rendering into it
			// shears the image (#568 landscape bug). Rebuild this entry at
			// the new dims.
			if (impl->ag_fb_cache[i].fb != VK_NULL_HANDLE) {
				vk->vkDestroyFramebuffer(vk->device, impl->ag_fb_cache[i].fb, nullptr);
				impl->ag_fb_cache[i].fb = VK_NULL_HANDLE;
			}
			VkFramebufferCreateInfo fbci2 = {};
			fbci2.sType = VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO;
			fbci2.renderPass = impl->ag_rp;
			fbci2.attachmentCount = 1;
			fbci2.pAttachments = &color_view;
			fbci2.width = w;
			fbci2.height = h;
			fbci2.layers = 1;
			VkFramebuffer rfb = VK_NULL_HANDLE;
			if (vk->vkCreateFramebuffer(vk->device, &fbci2, nullptr, &rfb) != VK_SUCCESS) {
				U_LOG_W("alpha-gate: framebuffer rebuild (rotation) failed");
				return VK_NULL_HANDLE;
			}
			impl->ag_fb_cache[i].fb = rfb;
			impl->ag_fb_cache[i].w = w;
			impl->ag_fb_cache[i].h = h;
			U_LOG_W("alpha-gate: rebuilt fb for recycled view at new dims %ux%u (rotation guard, #568)", w, h);
			return rfb;
		}
	}
	if (impl->ag_fb_count >= 8) {
		// Swapchain recreate churned the compositor's view set — flush and
		// rebuild on demand (the recreate idled the device, so old FBs aren't
		// in flight). Same rationale as get_or_create_weave_fb.
		for (uint32_t i = 0; i < impl->ag_fb_count; i++) {
			if (impl->ag_fb_cache[i].fb != VK_NULL_HANDLE) {
				vk->vkDestroyFramebuffer(vk->device, impl->ag_fb_cache[i].fb, nullptr);
			}
			impl->ag_fb_cache[i] = {};
		}
		impl->ag_fb_count = 0;
	}
	VkFramebufferCreateInfo fbci = {};
	fbci.sType = VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO;
	fbci.renderPass = impl->ag_rp;
	fbci.attachmentCount = 1;
	fbci.pAttachments = &color_view;
	fbci.width = w;
	fbci.height = h;
	fbci.layers = 1;
	VkFramebuffer fb = VK_NULL_HANDLE;
	if (vk->vkCreateFramebuffer(vk->device, &fbci, nullptr, &fb) != VK_SUCCESS) {
		U_LOG_W("alpha-gate: framebuffer create failed");
		return VK_NULL_HANDLE;
	}
	impl->ag_fb_cache[impl->ag_fb_count].view = color_view;
	impl->ag_fb_cache[impl->ag_fb_count].fb = fb;
	impl->ag_fb_cache[impl->ag_fb_count].w = w;
	impl->ag_fb_cache[impl->ag_fb_count].h = h;
	impl->ag_fb_count++;
	return fb;
}

// ─── Pre-weave compose-under-bg (runtime#1073 T0) ───────────────────────────
//
// Ported from the Linux VK DP (drv_leia_linux/leia_display_processor_linux.c
// `compose_*`), which is itself the Vulkan port of the Windows
// `compose_run_pre_weave`. Same shader — shaders/compose_under_bg.frag, a
// byte-identical per-backend copy of ../drv_leia/shaders/.
//
// WHY it has to be pre-weave: the interlacer assigns R, G and B of one output
// pixel to DIFFERENT views, while RGBA carries ONE alpha per pixel. On the
// avatar's silhouette and inside the parallax de-occlusion band there is no
// correct single alpha — a_r and a_g genuinely differ — so the post-weave gate
// can only move the error around, which is what the thin chromatic fringe is.
// Compositing a background under each view while the views are still
// INDEPENDENT removes the mixed class entirely: the weaver then eats opaque
// pixels and the gate only has to answer the easy question ("was EVERY view
// transparent here?").
//
// PRODUCER-AGNOSTIC by construction: this pass never asks where the background
// came from, it just samples `bg2d_view`. T0 fills it with a runtime-drawn
// solid/gradient (base DP vtable slot 16, `set_background_2d`); T1
// (MediaProjection) and T2 (vendor `captureDisplay(excludeLayers=…)`) fill the
// same seam with real screen content and nothing here changes.
//
// Divergences from the Linux port, both forced by this DP being SELF-SUBMITTING
// (the compositor hands us VK_NULL_HANDLE for cmd_buffer):
//   1. own one-shot command buffer + submit, like alpha_gate_run (the wait that
//      used to follow moved onto the GPU as a semaphore — runtime#1073 L11);
//   2. the intermediate is created in the ATLAS's format, not a hardcoded
//      R8G8B8A8_UNORM, so an sRGB atlas keeps its transfer function through the
//      compose and CNSDK sees exactly the format it saw before.

// Reclaim the previous compose submit: bounded wait on its fence, then release
// the one-shot command buffer it owned. Since L11 the compose is no longer
// CPU-waited in its own frame, so this is the single point that makes reuse and
// teardown of the command buffer / descriptor set legal. Bounded (never
// UINT64_MAX) per the workspace-stability rules — a lost GPU must surface as a
// dropped compose, not a wedged render thread.
static const uint64_t kComposeReclaimTimeoutNs = 1000000000ULL; // 1 s

// Consume a binary semaphore that was signalled but whose intended waiter never
// ran (runtime#1073 L11). A binary semaphore may not be signalled twice without
// an intervening wait, so an abandoned signal would break EVERY later frame, not
// just this one — an empty batch is the cheapest legal way to swallow it.
// Off the happy path by construction; never per-frame.
static void
drain_semaphore(leia_dp_cnsdk *impl, VkSemaphore sem)
{
	struct vk_bundle *vk = impl->vk;
	if (sem == VK_NULL_HANDLE || vk == nullptr || vk->main_queue == nullptr) {
		return;
	}
	U_LOG_W("compose-under: draining an unconsumed weave semaphore (chain broke this frame)");
	VkPipelineStageFlags stage = VK_PIPELINE_STAGE_ALL_COMMANDS_BIT;
	VkSubmitInfo si = {};
	si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
	si.waitSemaphoreCount = 1;
	si.pWaitSemaphores = &sem;
	si.pWaitDstStageMask = &stage;
	if (vk->vkQueueSubmit(vk->main_queue->queue, 1, &si, VK_NULL_HANDLE) == VK_SUCCESS) {
		vk->vkQueueWaitIdle(vk->main_queue->queue);
	}
}

static bool
compose_reclaim(leia_dp_cnsdk *impl)
{
	struct vk_bundle *vk = impl->vk;
	if (vk == nullptr) {
		return false;
	}
	bool ok = true;
	if (impl->cmp_fence_armed && impl->cmp_fence != VK_NULL_HANDLE) {
		VkResult res =
		    vk->vkWaitForFences(vk->device, 1, &impl->cmp_fence, VK_TRUE, kComposeReclaimTimeoutNs);
		if (res != VK_SUCCESS) {
			// Lifecycle event, not per-frame: a compose that never completed
			// means the whole pass is untrustworthy this frame.
			U_LOG_W("compose-under: reclaim wait failed (%d) — skipping compose", res);
			ok = false;
		}
		impl->cmp_fence_armed = false;
	}
	if (impl->cmp_cmd != VK_NULL_HANDLE && impl->cmd_pool != VK_NULL_HANDLE) {
		vk->vkFreeCommandBuffers(vk->device, impl->cmd_pool, 1, &impl->cmp_cmd);
		impl->cmp_cmd = VK_NULL_HANDLE;
	}
	return ok;
}

static void
destroy_compose(leia_dp_cnsdk *impl)
{
	struct vk_bundle *vk = impl->vk;
	if (vk == nullptr) {
		return;
	}
	// Everything below is in-flight-sensitive; drain first (L11).
	compose_reclaim(impl);
	if (impl->cmp_pipeline != VK_NULL_HANDLE) {
		vk->vkDestroyPipeline(vk->device, impl->cmp_pipeline, nullptr);
		impl->cmp_pipeline = VK_NULL_HANDLE;
	}
	if (impl->cmp_pipeline_layout != VK_NULL_HANDLE) {
		vk->vkDestroyPipelineLayout(vk->device, impl->cmp_pipeline_layout, nullptr);
		impl->cmp_pipeline_layout = VK_NULL_HANDLE;
	}
	if (impl->cmp_desc_pool != VK_NULL_HANDLE) {
		vk->vkDestroyDescriptorPool(vk->device, impl->cmp_desc_pool, nullptr);
		impl->cmp_desc_pool = VK_NULL_HANDLE;
		impl->cmp_set = VK_NULL_HANDLE; // freed with the pool
	}
	if (impl->cmp_desc_layout != VK_NULL_HANDLE) {
		vk->vkDestroyDescriptorSetLayout(vk->device, impl->cmp_desc_layout, nullptr);
		impl->cmp_desc_layout = VK_NULL_HANDLE;
	}
	if (impl->cmp_sampler != VK_NULL_HANDLE) {
		vk->vkDestroySampler(vk->device, impl->cmp_sampler, nullptr);
		impl->cmp_sampler = VK_NULL_HANDLE;
	}
	if (impl->cmp_fill_fb != VK_NULL_HANDLE) {
		vk->vkDestroyFramebuffer(vk->device, impl->cmp_fill_fb, nullptr);
		impl->cmp_fill_fb = VK_NULL_HANDLE;
	}
	if (impl->cmp_fill_view != VK_NULL_HANDLE) {
		vk->vkDestroyImageView(vk->device, impl->cmp_fill_view, nullptr);
		impl->cmp_fill_view = VK_NULL_HANDLE;
	}
	if (impl->cmp_fill_img != VK_NULL_HANDLE) {
		vk->vkDestroyImage(vk->device, impl->cmp_fill_img, nullptr);
		impl->cmp_fill_img = VK_NULL_HANDLE;
	}
	if (impl->cmp_fill_mem != VK_NULL_HANDLE) {
		vk->vkFreeMemory(vk->device, impl->cmp_fill_mem, nullptr);
		impl->cmp_fill_mem = VK_NULL_HANDLE;
	}
	if (impl->cmp_rp != VK_NULL_HANDLE) {
		vk->vkDestroyRenderPass(vk->device, impl->cmp_rp, nullptr);
		impl->cmp_rp = VK_NULL_HANDLE;
	}
	if (impl->cmp_fence != VK_NULL_HANDLE) {
		vk->vkDestroyFence(vk->device, impl->cmp_fence, nullptr);
		impl->cmp_fence = VK_NULL_HANDLE;
	}
	if (impl->cmp_done_sem != VK_NULL_HANDLE) {
		vk->vkDestroySemaphore(vk->device, impl->cmp_done_sem, nullptr);
		impl->cmp_done_sem = VK_NULL_HANDLE;
	}
	if (impl->cmp_weave_sem != VK_NULL_HANDLE) {
		vk->vkDestroySemaphore(vk->device, impl->cmp_weave_sem, nullptr);
		impl->cmp_weave_sem = VK_NULL_HANDLE;
	}
	impl->cmp_fence_armed = false;
	impl->cmp_fill_w = 0;
	impl->cmp_fill_h = 0;
	impl->cmp_fmt = VK_FORMAT_UNDEFINED;
	impl->cmp_inited = false;
}

// Atlas-sized opaque intermediate the compose pass renders into and CNSDK then
// interlaces from. Recreated on a size change (mode switch / rotation).
static bool
compose_ensure_fill(leia_dp_cnsdk *impl, uint32_t w, uint32_t h, VkFormat fmt)
{
	struct vk_bundle *vk = impl->vk;
	if (impl->cmp_fill_img != VK_NULL_HANDLE && impl->cmp_fill_w == w && impl->cmp_fill_h == h) {
		return true;
	}
	if (impl->cmp_fill_fb != VK_NULL_HANDLE) {
		vk->vkDestroyFramebuffer(vk->device, impl->cmp_fill_fb, nullptr);
		impl->cmp_fill_fb = VK_NULL_HANDLE;
	}
	if (impl->cmp_fill_view != VK_NULL_HANDLE) {
		vk->vkDestroyImageView(vk->device, impl->cmp_fill_view, nullptr);
		impl->cmp_fill_view = VK_NULL_HANDLE;
	}
	if (impl->cmp_fill_img != VK_NULL_HANDLE) {
		vk->vkDestroyImage(vk->device, impl->cmp_fill_img, nullptr);
		impl->cmp_fill_img = VK_NULL_HANDLE;
	}
	if (impl->cmp_fill_mem != VK_NULL_HANDLE) {
		vk->vkFreeMemory(vk->device, impl->cmp_fill_mem, nullptr);
		impl->cmp_fill_mem = VK_NULL_HANDLE;
	}

	VkImageCreateInfo ici = {};
	ici.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
	ici.imageType = VK_IMAGE_TYPE_2D;
	ici.format = fmt;
	ici.extent = {w, h, 1};
	ici.mipLevels = 1;
	ici.arrayLayers = 1;
	ici.samples = VK_SAMPLE_COUNT_1_BIT;
	ici.tiling = VK_IMAGE_TILING_OPTIMAL;
	ici.usage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT;
	ici.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
	if (vk->vkCreateImage(vk->device, &ici, nullptr, &impl->cmp_fill_img) != VK_SUCCESS) {
		U_LOG_W("compose-under: fill image create failed");
		return false;
	}
	VkMemoryRequirements reqs;
	vk->vkGetImageMemoryRequirements(vk->device, impl->cmp_fill_img, &reqs);
	VkMemoryAllocateInfo mai = {};
	mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
	mai.allocationSize = reqs.size;
	if (!vk_get_memory_type(vk, reqs.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, &mai.memoryTypeIndex)) {
		U_LOG_W("compose-under: no device-local memory type");
		return false;
	}
	if (vk->vkAllocateMemory(vk->device, &mai, nullptr, &impl->cmp_fill_mem) != VK_SUCCESS) {
		U_LOG_W("compose-under: fill memory alloc failed");
		return false;
	}
	vk->vkBindImageMemory(vk->device, impl->cmp_fill_img, impl->cmp_fill_mem, 0);

	VkImageViewCreateInfo ivci = {};
	ivci.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
	ivci.image = impl->cmp_fill_img;
	ivci.viewType = VK_IMAGE_VIEW_TYPE_2D;
	ivci.format = fmt;
	ivci.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
	if (vk->vkCreateImageView(vk->device, &ivci, nullptr, &impl->cmp_fill_view) != VK_SUCCESS) {
		U_LOG_W("compose-under: fill view create failed");
		return false;
	}

	VkFramebufferCreateInfo fbci = {};
	fbci.sType = VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO;
	fbci.renderPass = impl->cmp_rp;
	fbci.attachmentCount = 1;
	fbci.pAttachments = &impl->cmp_fill_view;
	fbci.width = w;
	fbci.height = h;
	fbci.layers = 1;
	if (vk->vkCreateFramebuffer(vk->device, &fbci, nullptr, &impl->cmp_fill_fb) != VK_SUCCESS) {
		U_LOG_W("compose-under: fill framebuffer create failed");
		return false;
	}
	impl->cmp_fill_w = w;
	impl->cmp_fill_h = h;
	return true;
}

// Render pass + descriptor plumbing + pipeline. Rebuilt if the atlas format
// changes (the intermediate follows the atlas, see the header comment).
static bool
compose_ensure_pipeline(leia_dp_cnsdk *impl, VkFormat fmt)
{
	struct vk_bundle *vk = impl->vk;
	if (impl->cmp_inited && impl->cmp_fmt == fmt) {
		return true;
	}
	if (impl->cmp_inited) {
		destroy_compose(impl);
	}
	VkResult res;

	// Render pass: the fullscreen triangle overwrites every texel, so
	// LOAD_OP_DONT_CARE; ends in SHADER_READ so CNSDK can sample it straight
	// away with no extra barrier.
	{
		VkAttachmentDescription att = {};
		att.format = fmt;
		att.samples = VK_SAMPLE_COUNT_1_BIT;
		att.loadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
		att.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
		att.stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
		att.stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
		att.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
		att.finalLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
		VkAttachmentReference ref = {0, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL};
		VkSubpassDescription sub = {};
		sub.pipelineBindPoint = VK_PIPELINE_BIND_POINT_GRAPHICS;
		sub.colorAttachmentCount = 1;
		sub.pColorAttachments = &ref;
		VkRenderPassCreateInfo rpi = {};
		rpi.sType = VK_STRUCTURE_TYPE_RENDER_PASS_CREATE_INFO;
		rpi.attachmentCount = 1;
		rpi.pAttachments = &att;
		rpi.subpassCount = 1;
		rpi.pSubpasses = &sub;
		res = vk->vkCreateRenderPass(vk->device, &rpi, nullptr, &impl->cmp_rp);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: render pass failed: %d", res);
			return false;
		}
	}

	// Linear/clamp sampler — the backdrop is a small image stretched across
	// each tile, so linear filtering is what makes a gradient look like one.
	{
		VkSamplerCreateInfo si = {};
		si.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
		si.magFilter = VK_FILTER_LINEAR;
		si.minFilter = VK_FILTER_LINEAR;
		si.mipmapMode = VK_SAMPLER_MIPMAP_MODE_LINEAR;
		si.addressModeU = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
		si.addressModeV = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
		si.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
		si.maxLod = 1.0f;
		res = vk->vkCreateSampler(vk->device, &si, nullptr, &impl->cmp_sampler);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: sampler failed: %d", res);
			destroy_compose(impl);
			return false;
		}
	}

	// 3 bindings (atlas 0 + bg 1 + backdrop 2), matching the shared shader.
	// Android binds the runtime backdrop to 1 and again to 2 (dummy) and pushes
	// has_backdrop = 0 — see the shader header.
	{
		VkDescriptorSetLayoutBinding bs[3] = {};
		for (uint32_t i = 0; i < 3; i++) {
			bs[i].binding = i;
			bs[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
			bs[i].descriptorCount = 1;
			bs[i].stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
		}
		VkDescriptorSetLayoutCreateInfo ci = {};
		ci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
		ci.bindingCount = 3;
		ci.pBindings = bs;
		res = vk->vkCreateDescriptorSetLayout(vk->device, &ci, nullptr, &impl->cmp_desc_layout);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: desc layout failed: %d", res);
			destroy_compose(impl);
			return false;
		}
	}

	// 32-byte push constant: 2*vec2 + uvec2 + 2*uint (compose_under_bg.frag).
	{
		VkPushConstantRange pc = {};
		pc.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
		pc.offset = 0;
		pc.size = 32;
		VkPipelineLayoutCreateInfo pli = {};
		pli.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
		pli.setLayoutCount = 1;
		pli.pSetLayouts = &impl->cmp_desc_layout;
		pli.pushConstantRangeCount = 1;
		pli.pPushConstantRanges = &pc;
		res = vk->vkCreatePipelineLayout(vk->device, &pli, nullptr, &impl->cmp_pipeline_layout);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: pipeline layout failed: %d", res);
			destroy_compose(impl);
			return false;
		}
	}

	{
		VkDescriptorPoolSize size = {VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 3};
		VkDescriptorPoolCreateInfo dpi = {};
		dpi.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
		dpi.maxSets = 1;
		dpi.poolSizeCount = 1;
		dpi.pPoolSizes = &size;
		res = vk->vkCreateDescriptorPool(vk->device, &dpi, nullptr, &impl->cmp_desc_pool);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: desc pool failed: %d", res);
			destroy_compose(impl);
			return false;
		}
		VkDescriptorSetAllocateInfo ai = {};
		ai.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
		ai.descriptorPool = impl->cmp_desc_pool;
		ai.descriptorSetCount = 1;
		ai.pSetLayouts = &impl->cmp_desc_layout;
		res = vk->vkAllocateDescriptorSets(vk->device, &ai, &impl->cmp_set);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: desc set alloc failed: %d", res);
			destroy_compose(impl);
			return false;
		}
	}

	{
		VkShaderModule vs =
		    ag_create_shader_module(vk, shaders_fullscreen_tri_vert, sizeof(shaders_fullscreen_tri_vert));
		VkShaderModule fs = ag_create_shader_module(vk, shaders_compose_under_bg_frag,
		                                            sizeof(shaders_compose_under_bg_frag));
		if (vs == VK_NULL_HANDLE || fs == VK_NULL_HANDLE) {
			if (vs != VK_NULL_HANDLE) {
				vk->vkDestroyShaderModule(vk->device, vs, nullptr);
			}
			if (fs != VK_NULL_HANDLE) {
				vk->vkDestroyShaderModule(vk->device, fs, nullptr);
			}
			U_LOG_W("compose-under: shader module create failed");
			destroy_compose(impl);
			return false;
		}
		VkPipelineShaderStageCreateInfo stages[2] = {};
		stages[0].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
		stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
		stages[0].module = vs;
		stages[0].pName = "main";
		stages[1].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
		stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
		stages[1].module = fs;
		stages[1].pName = "main";

		VkPipelineVertexInputStateCreateInfo vi = {};
		vi.sType = VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO;
		VkPipelineInputAssemblyStateCreateInfo ia = {};
		ia.sType = VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO;
		ia.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;
		VkPipelineViewportStateCreateInfo vps = {};
		vps.sType = VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO;
		vps.viewportCount = 1;
		vps.scissorCount = 1;
		VkPipelineRasterizationStateCreateInfo rs = {};
		rs.sType = VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO;
		rs.polygonMode = VK_POLYGON_MODE_FILL;
		rs.cullMode = VK_CULL_MODE_NONE;
		rs.frontFace = VK_FRONT_FACE_COUNTER_CLOCKWISE;
		rs.lineWidth = 1.0f;
		VkPipelineMultisampleStateCreateInfo ms = {};
		ms.sType = VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO;
		ms.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;
		// Same footgun as the gate: no inherited blend, all 4 channels written.
		// The compose output is opaque by construction (out.a = 1), and it MUST
		// land verbatim — a src-over blend here would re-introduce the very
		// partial alpha the pass exists to eliminate.
		VkPipelineColorBlendAttachmentState ba = {};
		ba.blendEnable = VK_FALSE;
		ba.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT |
		                    VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;
		VkPipelineColorBlendStateCreateInfo cb = {};
		cb.sType = VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO;
		cb.attachmentCount = 1;
		cb.pAttachments = &ba;
		VkDynamicState dyn[2] = {VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR};
		VkPipelineDynamicStateCreateInfo dynstate = {};
		dynstate.sType = VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO;
		dynstate.dynamicStateCount = 2;
		dynstate.pDynamicStates = dyn;
		VkGraphicsPipelineCreateInfo pi = {};
		pi.sType = VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO;
		pi.stageCount = 2;
		pi.pStages = stages;
		pi.pVertexInputState = &vi;
		pi.pInputAssemblyState = &ia;
		pi.pViewportState = &vps;
		pi.pRasterizationState = &rs;
		pi.pMultisampleState = &ms;
		pi.pColorBlendState = &cb;
		pi.pDynamicState = &dynstate;
		pi.layout = impl->cmp_pipeline_layout;
		pi.renderPass = impl->cmp_rp;
		pi.subpass = 0;
		res = vk->vkCreateGraphicsPipelines(vk->device, VK_NULL_HANDLE, 1, &pi, nullptr, &impl->cmp_pipeline);
		vk->vkDestroyShaderModule(vk->device, fs, nullptr);
		vk->vkDestroyShaderModule(vk->device, vs, nullptr);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: pipeline create failed: %d", res);
			destroy_compose(impl);
			return false;
		}
	}

	{
		VkFenceCreateInfo fci = {};
		fci.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
		res = vk->vkCreateFence(vk->device, &fci, nullptr, &impl->cmp_fence);
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: fence create failed: %d", res);
			destroy_compose(impl);
			return false;
		}
		impl->cmp_fence_armed = false;
	}

	{
		// runtime#1073 L11: the two links of the on-GPU chain
		// compose -> weave -> alpha gate. Binary (one-shot) semaphores are
		// safe with a single in-flight compose because the gate drains the
		// queue at the end of every composed frame; the fast path is gated on
		// exactly that (see compose_pre_weave's `frame_drains`).
		VkSemaphoreCreateInfo sci = {};
		sci.sType = VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO;
		res = vk->vkCreateSemaphore(vk->device, &sci, nullptr, &impl->cmp_done_sem);
		if (res == VK_SUCCESS) {
			res = vk->vkCreateSemaphore(vk->device, &sci, nullptr, &impl->cmp_weave_sem);
		}
		if (res != VK_SUCCESS) {
			U_LOG_W("compose-under: semaphore create failed: %d", res);
			destroy_compose(impl);
			return false;
		}
	}

	impl->cmp_fmt = fmt;
	impl->cmp_inited = true;
	U_LOG_W("Leia CNSDK DP: compose-under-bg pipeline ready (runtime#1073 T0, fmt=%d)", (int)fmt);
	return true;
}

// `debug.dxr.leia.bgdebug=1`: the compose pass outputs the BACKGROUND ONLY
// across the whole tile and the post-weave alpha gate is skipped. Both tiles
// then carry identical, zero-disparity content, so `adb exec-out screencap` of
// the woven panel reads back as the backdrop image itself — which is what turns
// "is the backdrop arriving, and is it mapped the way the producer sent it?"
// into a one-glance check rather than a squint at the de-occlusion band (#174).
// Same knob as the Linux DP's DXR_LEIA_BG_DEBUG. Cached: __system_property_get
// isn't free and a mid-session flip would race in-flight frames.
static bool
bg_debug_enabled()
{
	static int cached = -1;
	if (cached < 0) {
		cached = 0;
#ifdef XRT_OS_ANDROID
		char buf[PROP_VALUE_MAX] = {0};
		if (__system_property_get("debug.dxr.leia.bgdebug", buf) > 0 && buf[0] == '1') {
			cached = 1;
		}
#endif
		if (cached == 1) {
			U_LOG_W("Leia CNSDK DP: bg-debug ON — compose outputs the backdrop only,"
			        " alpha gate skipped (#174)");
		}
	}
	return cached == 1;
}

// Composite the tiled atlas OVER the bound backdrop into an opaque
// intermediate and return its view for CNSDK to interlace. VK_NULL_HANDLE ⟹
// caller weaves the raw atlas (today's live alpha-gate behaviour): transparency
// off, no backdrop bound, or any setup failure.
static VkImageView
compose_pre_weave(leia_dp_cnsdk *impl, VkImageView atlas_view, uint32_t atlas_w, uint32_t atlas_h,
                  uint32_t tile_columns, uint32_t tile_rows, VkFormat atlas_fmt, bool frame_drains,
                  VkSemaphore *out_wait_sem)
{
	DXR_ATRACE("dxr_dp:compose_pre_weave");
	struct vk_bundle *vk = impl->vk;
	*out_wait_sem = VK_NULL_HANDLE;
	if (!impl->transparent_bg_enabled || impl->bg2d_view == VK_NULL_HANDLE) {
		return VK_NULL_HANDLE;
	}
	if (vk == nullptr || vk->main_queue == nullptr || impl->cmd_pool == VK_NULL_HANDLE) {
		return VK_NULL_HANDLE;
	}
	// Release last frame's command buffer and make the single descriptor set
	// writable again. In the steady state the fence is long signalled, so this
	// costs nothing — it is the cost the CPU used to pay INSIDE the frame. It
	// runs BEFORE the ensure_* calls because a format/size change tears the
	// intermediate down, and that must not happen under an in-flight compose.
	if (!compose_reclaim(impl)) {
		return VK_NULL_HANDLE;
	}
	if (!compose_ensure_pipeline(impl, atlas_fmt) || !compose_ensure_fill(impl, atlas_w, atlas_h, atlas_fmt)) {
		return VK_NULL_HANDLE;
	}

	// atlas (0) = the app's premultiplied per-view content; bg (1) = the
	// runtime backdrop; backdrop (2) = the same image again, unused
	// (has_backdrop = 0) purely to keep the descriptor set complete.
	VkDescriptorImageInfo infos[3] = {};
	infos[0].sampler = impl->cmp_sampler;
	infos[0].imageView = atlas_view;
	infos[0].imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
	infos[1].sampler = impl->cmp_sampler;
	infos[1].imageView = impl->bg2d_view;
	infos[1].imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
	infos[2] = infos[1];
	VkWriteDescriptorSet writes[3] = {};
	for (uint32_t i = 0; i < 3; i++) {
		writes[i].sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
		writes[i].dstSet = impl->cmp_set;
		writes[i].dstBinding = i;
		writes[i].descriptorCount = 1;
		writes[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
		writes[i].pImageInfo = &infos[i];
	}
	vk->vkUpdateDescriptorSets(vk->device, 3, writes, 0, nullptr);

	VkCommandBufferAllocateInfo cbai = {};
	cbai.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
	cbai.commandPool = impl->cmd_pool;
	cbai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
	cbai.commandBufferCount = 1;
	VkCommandBuffer cmd = VK_NULL_HANDLE;
	if (vk->vkAllocateCommandBuffers(vk->device, &cbai, &cmd) != VK_SUCCESS) {
		return VK_NULL_HANDLE;
	}
	VkCommandBufferBeginInfo bi = {};
	bi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
	bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
	vk->vkBeginCommandBuffer(cmd, &bi);

	const int64_t t_start_ns = os_monotonic_get_ns();

	VkRenderPassBeginInfo rpbi = {};
	rpbi.sType = VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO;
	rpbi.renderPass = impl->cmp_rp;
	rpbi.framebuffer = impl->cmp_fill_fb;
	rpbi.renderArea.offset = {0, 0};
	rpbi.renderArea.extent = {atlas_w, atlas_h};
	vk->vkCmdBeginRenderPass(cmd, &rpbi, VK_SUBPASS_CONTENTS_INLINE);
	vk->vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, impl->cmp_pipeline);
	vk->vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, impl->cmp_pipeline_layout, 0, 1,
	                            &impl->cmp_set, 0, nullptr);

	struct
	{
		float bg_uv_origin[2];
		float bg_uv_extent[2];
		uint32_t tile_count[2];
		uint32_t has_backdrop;
		uint32_t pad;
	} push = {};
	// The runtime backdrop is already canvas-space: it covers exactly the
	// window/canvas the atlas tiles depict, so the whole 0..1 range maps to each
	// tile. (A T1/T2 capture producer would instead push the window's sub-rect
	// on the panel here — the only line that would change.)
	push.bg_uv_origin[0] = 0.0f;
	push.bg_uv_origin[1] = 0.0f;
	push.bg_uv_extent[0] = 1.0f;
	push.bg_uv_extent[1] = 1.0f;
	push.tile_count[0] = tile_columns;
	push.tile_count[1] = tile_rows;
	push.has_backdrop = 0u; // no Local2D under-layer on Android yet (#491)
	push.pad = bg_debug_enabled() ? 1u : 0u;
	vk->vkCmdPushConstants(cmd, impl->cmp_pipeline_layout, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(push), &push);

	VkViewport vp = {0.0f, 0.0f, (float)atlas_w, (float)atlas_h, 0.0f, 1.0f};
	VkRect2D sc = {{0, 0}, {atlas_w, atlas_h}};
	vk->vkCmdSetViewport(cmd, 0, 1, &vp);
	vk->vkCmdSetScissor(cmd, 0, 1, &sc);
	vk->vkCmdDraw(cmd, 3, 1, 0, 0);
	vk->vkCmdEndRenderPass(cmd);
	vk->vkEndCommandBuffer(cmd);

	// runtime#1073 L11 — express the compose→weave dependency ON THE GPU.
	//
	// CNSDK's `do_post_process` submits the interlace pass itself, and its
	// `imageAvailableSemaphore` IS a real wait: the interlacer stores it and
	// hands it to the submit whose command buffer samples the source views
	// (leia/sdk/interlacer.cpp DoPostProcess → ApplyInterlacing →
	// CRendererVulkan::Apply2DEffect, honoured at `currentPass == 0`). So the
	// old comment here — "CNSDK exposes no wait-semaphore hook" — was wrong; the
	// hook existed and was being passed NULL. Signalling it instead of blocking
	// the render thread on `vkWaitForFences` is the whole of L11.
	//
	// The fence is still armed, but nobody waits it this frame: it is the
	// reclaim guard for the NEXT compose (see compose_reclaim).
	//
	// FALLBACK: the fast path needs the queue to be drained once per composed
	// frame, because a single intermediate image + a single descriptor set are
	// reused every frame and only the drain keeps frame N+1's compose from
	// overwriting what frame N's weave is still reading. The post-weave alpha
	// gate provides exactly that drain — so when it will NOT run (bg-debug, or a
	// tile layout the gate doesn't handle) we keep the pre-L11 synchronous wait
	// rather than trade a measured stall for an unproven race.
	const bool gpu_sync = frame_drains && impl->cmp_done_sem != VK_NULL_HANDLE;

	VkSubmitInfo si = {};
	si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
	si.commandBufferCount = 1;
	si.pCommandBuffers = &cmd;
	if (gpu_sync) {
		si.signalSemaphoreCount = 1;
		si.pSignalSemaphores = &impl->cmp_done_sem;
	}
	vk->vkResetFences(vk->device, 1, &impl->cmp_fence);
	VkResult res = vk->vkQueueSubmit(vk->main_queue->queue, 1, &si, impl->cmp_fence);
	if (res == VK_SUCCESS) {
		impl->cmp_fence_armed = true;
		impl->cmp_cmd = cmd; // freed at the next reclaim, never while in flight
		if (gpu_sync) {
			*out_wait_sem = impl->cmp_done_sem;
		} else {
			// Pre-L11 behaviour. Wait on OUR fence, not the queue:
			// vkQueueWaitIdle would also drain the compositor's unrelated
			// frame submissions on the same queue.
			vk->vkWaitForFences(vk->device, 1, &impl->cmp_fence, VK_TRUE,
			                    kComposeReclaimTimeoutNs);
		}
	} else {
		vk->vkFreeCommandBuffers(vk->device, impl->cmd_pool, 1, &cmd);
		U_LOG_W("compose-under: submit failed: %d", res);
		return VK_NULL_HANDLE;
	}

	{
		// Cost accounting: what this measures is the CPU time the render thread
		// spends in the pass — which is the number that decides whether T0 can
		// ever be on by default. Before L11 it also included a fence wait for
		// the pass's GPU completion (2.9 ms/frame IPC, ~1.5 ms in-process); on
		// the `gpu_sync` path there is no wait left to include, so the figure is
		// record + submit only and the GPU cost has moved off the critical path
		// into the weave's own wait. Throttled to one line per 300 composed
		// frames (never per-frame — that is log bloat, and it would perturb what
		// it measures).
		static int64_t accum_ns = 0;
		static uint32_t frames = 0;
		static bool logged_first = false;
		accum_ns += os_monotonic_get_ns() - t_start_ns;
		frames++;
		if (!logged_first) {
			logged_first = true;
			U_LOG_W("compose-under: FIRST composed frame — atlas=%ux%u tiles=%ux%u bg=%ux%u"
			        " (gate switches to mode 2 = flattened)",
			        atlas_w, atlas_h, tile_columns, tile_rows, impl->bg2d_w, impl->bg2d_h);
		}
		if (frames >= 300u) {
			U_LOG_W("COMPOSE_COST: %.3f ms/frame CPU over %u frames (atlas %ux%u, gpu_sync=%d)",
			        (double)accum_ns / (double)frames / 1.0e6, frames, atlas_w, atlas_h,
			        (int)gpu_sync);
			accum_ns = 0;
			frames = 0;
		}
	}
	return impl->cmp_fill_view;
}

// Base DP vtable slot 16. The runtime owns the image; we borrow the view for
// the NEXT process_atlas (it is in SHADER_READ_ONLY_OPTIMAL and outlives the
// call). VK_NULL_HANDLE / zero dims clears — the compose pass then no-ops and
// the DP falls back to weaving the raw atlas with the live alpha gate.
static void
set_background_2d_cnsdk(struct xrt_display_processor *xdp, VkImageView background_view, uint32_t width,
                        uint32_t height)
{
	leia_dp_cnsdk *impl = as_impl(xdp);
	VkImageView want = (width > 0u && height > 0u) ? background_view : VK_NULL_HANDLE;
	if (impl->bg2d_view != want) {
		U_LOG_W("Leia CNSDK DP: set_background_2d %s (%ux%u)", want != VK_NULL_HANDLE ? "bound" : "cleared",
		        width, height);
	}
	impl->bg2d_view = want;
	impl->bg2d_w = width;
	impl->bg2d_h = height;
}


// Alpha-gate mode (#568), read once from `debug.dxr.alphagate`:
//   1 (default) = woven per-pixel view-select — makes the parallax
//                 de-occlusion band see-through (the fix).
//   0           = legacy all-or-nothing mask (kept for on-device A/B; this is
//                 the mode that produced the black de-occlusion fringe).
// Cached because __system_property_get isn't free and a mid-session flip would
// race in-flight frames; force-stop the app to re-read.
uint32_t
alpha_gate_mode()
{
	static uint32_t cached = UINT32_MAX;
	if (cached != UINT32_MAX) {
		return cached;
	}
	cached = 1u; // default: the fix
#ifdef XRT_OS_ANDROID
	char buf[PROP_VALUE_MAX] = {0};
	if (__system_property_get("debug.dxr.alphagate", buf) > 0 && buf[0] == '0') {
		cached = 0u;
	}
#endif
	U_LOG_W("Leia CNSDK DP: alpha-gate mode=%u (1=woven-select, 0=legacy)", cached);
	return cached;
}

// Post-weave alpha-gate executor. Self-submits (the weave already submitted on
// its own command buffer). target_image is in COLOR_ATTACHMENT_OPTIMAL on entry
// and on exit.
//
// `weave_done_sem` (runtime#1073 L11) is CNSDK's `renderFinishedSemaphore` when
// the weave was chained on-GPU, else VK_NULL_HANDLE. It must be WAITED here:
// with the compose's CPU stall gone the weave is genuinely still in flight when
// this runs, so "submitted later on the same queue" no longer implies "ordered
// after". Returns false without submitting if the gate could not run — the
// caller then has to drain the semaphore itself, because a binary semaphore
// left signalled would corrupt the next frame.
bool
alpha_gate_run(leia_dp_cnsdk *impl,
               VkImage target_image,
               VkImageView atlas_view,
               uint32_t w,
               uint32_t h,
               uint32_t tile_columns,
               uint32_t tile_rows,
               VkFormat target_format,
               int32_t canvas_offset_x,
               int32_t canvas_offset_y,
               uint32_t canvas_width,
               uint32_t canvas_height,
               bool flattened,
               VkSemaphore weave_done_sem)
{
	DXR_ATRACE("dxr_dp:alpha_gate_run");
	struct vk_bundle *vk = impl->vk;
	if (vk->main_queue == nullptr) {
		return false;
	}
	if (!alpha_gate_ensure_pipeline(impl, target_format)) {
		return false;
	}
	if (!alpha_gate_ensure_strip(impl, w, h, target_format)) {
		return false;
	}
	VkFramebuffer fb = alpha_gate_get_fb(impl, w, h);
	if (fb == VK_NULL_HANDLE) {
		return false;
	}

	// Always-on diagnostic, re-logged whenever the geometry changes (e.g. on a
	// portrait⇄landscape rotation, #568) so a device log shows exactly what the
	// gate sampled in each orientation. The gate is driven entirely by these
	// per-frame target + tile dims — no worst-case/portrait assumptions.
	{
		static uint32_t last_w = 0, last_h = 0, last_c = 0, last_r = 0;
		if (w != last_w || h != last_h || tile_columns != last_c || tile_rows != last_r) {
			last_w = w; last_h = h; last_c = tile_columns; last_r = tile_rows;
			U_LOG_W("AG_GEO: target=%ux%u tiles=%ux%u mode=%u (strip+fb+viewport all driven by this target)",
			        w, h, tile_columns, tile_rows, flattened ? 2u : alpha_gate_mode());
		}
	}

	// The CNSDK weave self-submitted (possibly on its own queue), and its
	// color-attachment writes to target_image must be complete + visible before
	// we copy/sample it.
	//
	// runtime#1073 L11 took the "future optimization" this comment used to
	// promise: when the weave was chained on-GPU we hold its
	// `renderFinishedSemaphore` and express the dependency as a wait on THIS
	// submit instead of idling the device from the render thread. Cross-queue is
	// fine — a binary semaphore is device-scoped. The vkDeviceWaitIdle hammer
	// survives only for the un-chained fallback (bg-debug / unhandled tile
	// layout), where nothing else orders the weave against this pass.
	const bool gate_waits_weave = weave_done_sem != VK_NULL_HANDLE;
	if (!gate_waits_weave) {
		vk->vkDeviceWaitIdle(vk->device);
	}

	// Descriptors: 0 = strip copy (woven backbuffer), 1 = original premultiplied
	// atlas, 2 = dummy backdrop (= strip view; has_backdrop pushed 0 — no Local2D
	// under-layer on Android yet). The atlas is already SHADER_READ_ONLY_OPTIMAL
	// (compositor invariant; CNSDK only sampled it).
	VkDescriptorImageInfo infos[3] = {};
	infos[0].sampler = impl->ag_sampler;
	infos[0].imageView = impl->ag_strip_view;
	infos[0].imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
	infos[1].sampler = impl->ag_sampler;
	infos[1].imageView = atlas_view;
	infos[1].imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
	infos[2].sampler = impl->ag_sampler;
	infos[2].imageView = impl->ag_strip_view; // dummy
	infos[2].imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
	VkWriteDescriptorSet writes[3] = {};
	for (uint32_t i = 0; i < 3; i++) {
		writes[i].sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
		writes[i].dstSet = impl->ag_set;
		writes[i].dstBinding = i;
		writes[i].descriptorCount = 1;
		writes[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
		writes[i].pImageInfo = &infos[i];
	}
	vk->vkUpdateDescriptorSets(vk->device, 3, writes, 0, nullptr);

	// One-shot command buffer (self-submit; compositor's cmd is VK_NULL_HANDLE).
	VkCommandBufferAllocateInfo cbai = {};
	cbai.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
	cbai.commandPool = impl->cmd_pool;
	cbai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
	cbai.commandBufferCount = 1;
	VkCommandBuffer cmd = VK_NULL_HANDLE;
	if (vk->vkAllocateCommandBuffers(vk->device, &cbai, &cmd) != VK_SUCCESS) {
		return false;
	}
	VkCommandBufferBeginInfo bi = {};
	bi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
	bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
	vk->vkBeginCommandBuffer(cmd, &bi);

	// target COLOR_ATTACHMENT_OPTIMAL (weave exit) → TRANSFER_SRC;
	// strip UNDEFINED → TRANSFER_DST.
	VkImageMemoryBarrier pre[2] = {};
	pre[0].sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
	pre[0].srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT;
	pre[0].dstAccessMask = VK_ACCESS_TRANSFER_READ_BIT;
	pre[0].oldLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
	pre[0].newLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
	pre[0].srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	pre[0].dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	pre[0].image = target_image;
	pre[0].subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
	pre[1].sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
	pre[1].srcAccessMask = 0;
	pre[1].dstAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT;
	pre[1].oldLayout = VK_IMAGE_LAYOUT_UNDEFINED;
	pre[1].newLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
	pre[1].srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	pre[1].dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	pre[1].image = impl->ag_strip_img;
	pre[1].subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
	vk->vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT,
	    VK_PIPELINE_STAGE_TRANSFER_BIT, 0, 0, nullptr, 0, nullptr, 2, pre);

	VkImageCopy region = {};
	region.srcSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
	region.dstSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
	region.extent = {w, h, 1};
	vk->vkCmdCopyImage(cmd, target_image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
	    impl->ag_strip_img, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &region);

	// target TRANSFER_SRC → COLOR_ATTACHMENT (gate draws into it);
	// strip TRANSFER_DST → SHADER_READ (sampled as backbuffer).
	VkImageMemoryBarrier mid[2] = {};
	mid[0].sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
	mid[0].srcAccessMask = VK_ACCESS_TRANSFER_READ_BIT;
	mid[0].dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT;
	mid[0].oldLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
	mid[0].newLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
	mid[0].srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	mid[0].dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	mid[0].image = target_image;
	mid[0].subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
	mid[1].sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
	mid[1].srcAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT;
	mid[1].dstAccessMask = VK_ACCESS_SHADER_READ_BIT;
	mid[1].oldLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
	mid[1].newLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
	mid[1].srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	mid[1].dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	mid[1].image = impl->ag_strip_img;
	mid[1].subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
	vk->vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_TRANSFER_BIT,
	    VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT,
	    0, 0, nullptr, 0, nullptr, 2, mid);

	VkRenderPassBeginInfo rpbi = {};
	rpbi.sType = VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO;
	rpbi.renderPass = impl->ag_rp;
	rpbi.framebuffer = fb;
	rpbi.renderArea.offset = {0, 0};
	rpbi.renderArea.extent = {w, h};
	vk->vkCmdBeginRenderPass(cmd, &rpbi, VK_SUBPASS_CONTENTS_INLINE);

	vk->vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, impl->ag_pipeline);
	vk->vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, impl->ag_pipeline_layout, 0, 1,
	    &impl->ag_set, 0, nullptr);

	struct {
		uint32_t tile_count[2];
		uint32_t has_backdrop;
		uint32_t mode;
		float    canvas[4];   // normalized (offset.x, offset.y, extent.x, extent.y)
	} push = {};
	push.tile_count[0] = tile_columns;
	push.tile_count[1] = tile_rows;
	push.has_backdrop = 0u;            // no Local2D under-layer on Android yet (#491)
	// runtime#1073 T0: when the compose pass actually ran, the band is already
	// opaque over a real backdrop, so the gate must NOT try to reconstruct
	// per-pixel alpha for it — mode 2 (flattened) keeps it, and only punches
	// through where every view was transparent. Otherwise the pre-#1073
	// behaviour, still A/B-able with debug.dxr.alphagate.
	push.mode = flattened ? 2u : alpha_gate_mode();
	// XR_DXR_display_zones (#568): the canvas sub-rect the weave occupies, in
	// normalized target coords. A zero/empty rect means the content fills the
	// target → (0,0,1,1), the identity that reproduces the pre-zone behavior.
	if (canvas_width > 0u && canvas_height > 0u && w > 0u && h > 0u) {
		push.canvas[0] = (float)canvas_offset_x / (float)w;
		push.canvas[1] = (float)canvas_offset_y / (float)h;
		push.canvas[2] = (float)canvas_width   / (float)w;
		push.canvas[3] = (float)canvas_height  / (float)h;
	} else {
		push.canvas[0] = 0.0f; push.canvas[1] = 0.0f;
		push.canvas[2] = 1.0f; push.canvas[3] = 1.0f;
	}
	vk->vkCmdPushConstants(cmd, impl->ag_pipeline_layout, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(push), &push);

	VkViewport vp = {0.0f, 0.0f, (float)w, (float)h, 0.0f, 1.0f};
	VkRect2D sc = {{0, 0}, {w, h}};
	vk->vkCmdSetViewport(cmd, 0, 1, &vp);
	vk->vkCmdSetScissor(cmd, 0, 1, &sc);
	vk->vkCmdDraw(cmd, 3, 1, 0, 0);
	vk->vkCmdEndRenderPass(cmd);

	vk->vkEndCommandBuffer(cmd);
	// ALL_COMMANDS, not TRANSFER: the batch opens with a barrier whose source
	// scope is the weave's COLOR_ATTACHMENT_OUTPUT writes, and the semaphore wait
	// has to cover that barrier, not just the transfer that follows it. The gate
	// is one pass — there is nothing here for a narrower stage to overlap with.
	const VkPipelineStageFlags weave_wait_stage = VK_PIPELINE_STAGE_ALL_COMMANDS_BIT;
	VkSubmitInfo si = {};
	si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
	si.commandBufferCount = 1;
	si.pCommandBuffers = &cmd;
	if (gate_waits_weave) {
		si.waitSemaphoreCount = 1;
		si.pWaitSemaphores = &weave_done_sem;
		si.pWaitDstStageMask = &weave_wait_stage;
	}
	// The queue drain stays: xrEndFrame must see the target ready, and it is
	// also what keeps ONE compose in flight — the invariant the L11 fast path is
	// gated on (single intermediate image + single descriptor set).
	const bool submitted = vk->vkQueueSubmit(vk->main_queue->queue, 1, &si, VK_NULL_HANDLE) == VK_SUCCESS;
	if (submitted) {
		vk->vkQueueWaitIdle(vk->main_queue->queue);
	}
	vk->vkFreeCommandBuffers(vk->device, impl->cmd_pool, 1, &cmd);
	DXR_HW_DBG_ONCE("alpha_gate_run: first gated frame (%ux%u tiles=%ux%u)", w, h, tile_columns, tile_rows);
	return submitted;
}

