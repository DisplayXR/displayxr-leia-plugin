# Bash twin of fetch-neurd-headers.ps1: fetch the NeurD public headers from the
# PRIVATE LeiaInc/media_sdk repo at a pinned ref, for the conversion provider's
# POSIX arm (src/conv_leia, CPU transport).
#
# The headers are Leia-private: they land in a gitignored directory
# (NeurD-SDK-<ref>/include) and must never be committed or re-hosted on this
# public repo -- same rule as the SR SDK.
#
# Auth: `gh` with an account (or GH_TOKEN) that can read the repo.
# Exit 0 = headers ready; 1 = fetch failed. Callers treat failure as SOFT: the
# provider is not built and the rest of the plug-in builds unchanged.
#
# Usage: fetch-neurd-headers.sh <repo> <ref> <dest>
set -euo pipefail
REPO="${1:?usage: $0 <repo> <ref> <dest>}"
REF="${2:?usage: $0 <repo> <ref> <dest>}"
DEST="${3:?usage: $0 <repo> <ref> <dest>}"
INC="$DEST/include"

get() { gh api "repos/$REPO/contents/$1?ref=$REF" -H 'Accept: application/vnd.github.raw'; }

if ! {
    mkdir -p "$INC"
    # NeurD.h includes NeurD_version.h and _NeurD_detail.h; the latter includes
    # _NeurD_table.h. That is the whole closure.
    for f in NeurD.h _NeurD_detail.h _NeurD_table.h; do
        get "sdk/$f" >"$INC/$f"
    done
    # NeurD_version.h is generated by media_sdk's CMake from NeurD_version.h.in and
    # the top-level project(mediasdk ... VERSION "x.y.z"). Reproduce that exactly.
    ver="$(get CMakeLists.txt | grep -oP 'project\s*\(\s*mediasdk[^)]*VERSION\s+"?\K[0-9]+\.[0-9]+\.[0-9]+' | head -1)"
    [ -n "$ver" ]
    IFS=. read -r MA MI PA <<<"$ver"
    get sdk/NeurD_version.h.in |
        sed -e "s/@PROJECT_VERSION_MAJOR@/$MA/" -e "s/@PROJECT_VERSION_MINOR@/$MI/" -e "s/@PROJECT_VERSION_PATCH@/$PA/" \
            >"$INC/NeurD_version.h"
    echo "NeurD headers $ver ($REPO@$REF) -> $INC"
}; then
    echo "WARNING: NeurD header fetch failed ($REPO@$REF); the conversion provider will not be built." >&2
    echo "         Needs gh auth with read access to $REPO (gh auth login / GH_TOKEN)." >&2
    exit 1
fi
